<h2>Collecting from a depot</h2>

<p>
  Anything on the site can be collected instead of delivered. Order in the usual way and
  choose the depot you want at the checkout — Halifax, Elland, Rochdale, Barnsley,
  Warrington, Stockton-on-Tees, Preston or Doncaster. There is no carriage on a collected
  order. If the depot does not hold a line it comes across on the overnight trunk from
  Elland, which adds a day.
</p>

<p>
  Do not set off until you hear from us. A text message goes to the mobile number on the
  order the moment the goods are picked and on the counter waiting; it names the depot and
  gives the order number. Orders are held for five working days, after which they go back
  on the shelf and the account is credited.
</p>

<p>
  Bring the order number with you. The counter staff will find the order on that alone;
  they do not need a printout. If somebody else is collecting on your behalf, give them
  the order number and make sure they can name the account, because goods on a credit
  account are only released against a signature and a name we recognise.
</p>

<p>
  Trade counters open at seven in the morning, which is before most sites
  start, and close at five, or noon on a Saturday. Elland is the only counter open through
  the lunch hour. The counters are shut on Sundays and bank holidays.
</p>
