<h2>Delivery times and carriage</h2>

<p>
  Anything held in stock and ordered before four o'clock on a working day leaves Elland
  that evening for delivery the next working day. Orders placed after the cut-off go on
  the following evening's run. The cut-off is the time the order reaches us, not the time
  you started filling the basket, so a large order is best placed with a few minutes in
  hand.
</p>

<p>
  Carriage is charged at a flat rate per delivery and is free on orders over seventy-five
  pounds net of value added tax. The figure is worked out on the goods only; carriage
  already on the order and the tax do not count towards it. Deliveries to the Scottish
  Highlands, the islands, Northern Ireland and the Isle of Man are quoted individually
  because the hauliers charge us separately for them.
</p>

<p>
  Anything that has to travel on a pallet — resin, aggregate, long lengths of threaded
  bar, drums of oil — is quoted on its own and is not covered by the free carriage
  figure. The trade desk will price the pallet before the order is confirmed. See the
  note on pallet deliveries for what to expect when the lorry arrives.
</p>

<p>
  Saturday morning delivery can be arranged for the Halifax, Elland, Rochdale and Barnsley
  areas if the order is placed by noon on the Friday and the depot is told. It carries a
  surcharge. There are no deliveries on Sundays or bank holidays.
</p>
