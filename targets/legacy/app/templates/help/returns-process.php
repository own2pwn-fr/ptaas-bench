<h2>Sending something back</h2>

<p>
  Stock lines can be sent back within fourteen days of delivery provided they are unused,
  complete and in their original packaging with the labels intact. Fixings that have been
  split out of a box, blades that have been fitted and anything that has been on site and
  come back marked cannot be put back on the shelf and will not be credited.
</p>

<p>
  Ring the depot the goods came from before you send anything. They will give you a
  returns number, which should be written on the outside of the parcel and on the
  paperwork inside. Parcels that arrive without a number sit in goods-in until somebody
  works out whose they are, which is what holds the credit up.
</p>

<p>
  Special-order lines — anything brought in for you rather than held in stock, including
  cut lengths, non-catalogue sizes and manufacturer direct deliveries — are not
  returnable. The order acknowledgement says so against each line. Where a supplier will
  take an item back, they charge a restocking fee and we pass it on.
</p>

<p>
  If something has arrived damaged or is not what the delivery note says, tell the depot
  within three working days and keep the packaging. That is a shortage or a damage claim
  rather than a return and is dealt with straight away.
</p>
