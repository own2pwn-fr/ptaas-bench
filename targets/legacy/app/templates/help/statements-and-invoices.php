<h2>Statements and invoices</h2>

<p>
  An invoice is raised the day the goods leave us and is sent by e-mail to the address
  held against the account, with a copy in the post if the account is set up for paper. A
  statement listing every invoice, credit and payment for the period is issued on the last
  working day of the month.
</p>

<p>
  Standard terms are thirty days from statement, so goods bought at any point in March are
  due at the end of April. Payment is by bank transfer to the account shown at the foot of
  the statement, quoting the account code, or by card over the telephone. Please pay
  against the statement rather than against individual invoices; matching part payments to
  invoices is what causes most of the queries.
</p>

<p>
  Copies of invoices, credit notes, statements and signed delivery notes going back six
  years are in the account area of this site under statements, and can be downloaded as a
  portable document at any hour. That is quicker than ringing for a copy, and the
  documents are the same ones we hold.
</p>

<p>
  Credit control are at head office in Elland on 01422 000000 and will take a query on a
  line, arrange a copy delivery note, or discuss a limit. Ring them before a due date
  rather than after it: an account that goes over its limit or its terms stops
  automatically at every counter, and getting it released takes a telephone call that
  nobody wants to make from a site gate.
</p>
