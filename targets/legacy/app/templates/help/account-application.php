<h2>Applying for an account</h2>

<p>
  A credit account gets you your own agreed prices rather than the catalogue price, thirty
  days from statement to pay, delivery on account without paying at the door, and a
  monthly statement listing every invoice and credit. It also lets your people collect
  from any of the eight depots on your signature alone, which is what most site
  supervisors use it for.
</p>

<p>
  We ask for two trade references from suppliers you already buy from on credit, and a
  bank reference. Give the full company name, the registered number if you have one, the
  invoice address and the address goods should go to if they differ, and the name of the
  person who deals with purchase invoices. Sole traders and partnerships are welcome; we
  will usually ask for a personal guarantee.
</p>

<p>
  Applications take two working days once the references come back. Credit control at
  Elland set the opening limit, which is reviewed after six months of trading. In the
  meantime you can order on the site and pay by card, and anything bought that way is
  transferred onto the account once it opens.
</p>

<p>
  The application form is on the site under trade accounts. Fill it in, or ring the trade
  desk and they will take the details over the telephone and post the form out for
  signature.
</p>
