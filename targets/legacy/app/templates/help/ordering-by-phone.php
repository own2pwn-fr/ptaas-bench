<h2>Ordering by telephone</h2>

<p>
  The trade desk is on 01422 000000 from seven in the morning until half past five, Monday
  to Friday, and until noon on Saturday. It is the same desk for all eight depots; the
  order is routed to whichever depot holds the stock or, if it is going out on the evening
  run, to the warehouse at Elland.
</p>

<p>
  Have your account code to hand, the reference for each line and the quantity, and your
  own order number if your purchasing department needs one on the invoice. If you do not
  have the reference, the description off the printed catalogue page is usually enough for
  the desk to find it. Say whether the goods are for delivery or collection, and which
  depot, before prices are read back.
</p>

<p>
  References are read out a character at a time: the two letters, then the four digits in
  pairs, then the pack letter — so BT-1420-C comes back as "bravo tango, fourteen twenty,
  charlie". The desk will read the whole line back with the price and the quantity before
  the order is committed. Ask them to repeat it if the line is noisy; it saves a return
  later.
</p>

<p>
  An acknowledgement is sent by e-mail within the hour on every telephone order. Check the
  quantities and the delivery address on it, and ring straight back if something is wrong,
  because after four o'clock the order will already be on a pallet.
</p>
