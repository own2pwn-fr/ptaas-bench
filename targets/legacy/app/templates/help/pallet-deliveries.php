<h2>Pallet deliveries</h2>

<p>
  Heavy and bulky lines travel on a pallet with a haulier rather than on our own vans.
  Pallet deliveries are kerbside only. The driver will bring the pallet to the nearest
  hard standing that the lorry can safely reach and no further: he will not carry goods
  through a building, up a drive, into a compound or onto scaffolding, and he is not
  insured to go beyond the vehicle.
</p>

<p>
  Tell us when you order whether the site has a forklift. If it has not, ask for a tail
  lift vehicle and the pallet will be lowered to the ground on the back of the lorry. Tail
  lift vehicles are longer and heavier than a standard rigid, so they need a clear
  approach and somewhere to stop; narrow lanes, low bridges, unmade tracks and height
  barriers all have to be mentioned at the time of ordering or the delivery will fail.
</p>

<p>
  The haulier allows fifteen minutes on site. Waiting beyond that is charged by the
  quarter hour, as is a failed delivery where nobody is there to take the goods or the
  vehicle cannot get in. Both are passed on at cost with the haulier's ticket attached to
  the invoice.
</p>

<p>
  Somebody over eighteen must sign for the pallet. Count the packages against the delivery
  note before you sign, and if the shrink wrap is torn or a package is damaged write that
  on the note before signing it. A note signed clean is very hard to claim against
  afterwards.
</p>
