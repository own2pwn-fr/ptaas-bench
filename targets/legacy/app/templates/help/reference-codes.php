<h2>Understanding a reference code</h2>

<p>
  Every line we stock has a reference in the same shape: the letters BT, a dash, four
  digits, and on most lines a letter for the pack. BT-1420-C is line fourteen twenty in
  pack C. The prefix has been on the goods since the company started numbering them in
  1962 and never changes, so a reference off an old delivery note will still find the
  line today.
</p>

<p>
  The four digits are the line itself and are grouped by family rather than issued in the
  order the goods arrived. The 1000s are threaded fixings, the 2000s are anchors and
  fasteners for masonry, the 3000s are hand tools, the 4000s are power tool accessories
  and abrasives, the 5000s are site consumables, and the 8000s are the plant and hire
  spares. That is why two sizes of the same bolt sit next to each other in the numbering.
</p>

<p>
  The letter on the end is the pack, not the size: A is a single, B is a box of ten, C a
  box of a hundred, D a box of five hundred and E the trade tub or full carton. A line
  with no letter is sold as one only. Ordering BT-1420-C is a hundred of the same item,
  not one item numbered C, and it is the commonest slip on a written order.
</p>

<p>
  The printed catalogue uses exactly the same references. The page number in the corner of
  each catalogue entry has nothing to do with the reference and should not be quoted when
  ordering; the reference on its own is enough for the trade desk or for the quick
  reference box at the top of any page on this site.
</p>
